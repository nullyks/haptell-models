"""Append-only snapshots of generated models, using only the standard library."""

from __future__ import annotations

import functools
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
from datetime import datetime, timezone
from uuid import uuid4

ROOT = Path(__file__).resolve().parent
ARCHIVE = ROOT / "models"
FAMILIES = {
    "egg_box": ("generate_egg_box_stl.py", "output"),
    "balance_shift": ("generate_balance_shift_stl.py", "output/balance_shift"),
    "rounded_cube_box": ("generate_rounded_cube_box_stl.py", "output/rounded_cube_box"),
    "perforated_sphere": ("generate_perforated_sphere_stl.py", "output/perforated_sphere"),
}


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def snapshot(family: str, output_dir: Path, *, generated: bool = False) -> Path | None:
    """Preserve direct STL children; never recurse into other model families.

    Existing outputs have unknown source provenance. Only outputs just generated
    by the wrapped main function are associated with the captured source.
    An identical snapshot is reused, so unchanged runs do not duplicate meshes.
    """
    meshes = sorted(output_dir.glob("*.stl"))
    if not meshes:
        return None
    generator, _ = FAMILIES[family]
    sources = sorted(ROOT.glob("*.py")) + [ROOT / "requirements.txt"]
    files = {f"stl/{p.name}": digest(p) for p in meshes}
    files.update({f"source/{p.name}": digest(p) for p in sources})
    identity = hashlib.sha256(json.dumps(files, sort_keys=True).encode()).hexdigest()
    revisions = ARCHIVE / family / "revisions"
    revisions.mkdir(parents=True, exist_ok=True)
    for manifest in sorted(revisions.glob("*/manifest.json")):
        previous = json.loads(manifest.read_text(encoding="utf-8"))
        if previous["identity"] == identity and (not generated or previous["generated_with_captured_source"]):
            return manifest.parent

    now = datetime.now(timezone.utc)
    revision = now.strftime("%Y-%m-%d_%H%M%S") + "_" + uuid4().hex[:8]
    # Exclusive creation prevents accidental overwriting, even on name collision.
    destination = revisions / revision
    destination.mkdir(exist_ok=False)
    (destination / "stl").mkdir()
    (destination / "source").mkdir()
    for path in meshes:
        shutil.copy2(path, destination / "stl" / path.name)
    for path in sources:
        shutil.copy2(path, destination / "source" / path.name)
    # Verify all copies before permitting the generator to overwrite its output.
    for name, expected in files.items():
        if digest(destination / name) != expected:
            raise RuntimeError(f"Archive verification failed: {destination / name}")
    try:
        commit = subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=ROOT, text=True, stderr=subprocess.DEVNULL
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        commit = None
    metadata = {
        "family": family,
        "revision": revision,
        "archived_at_utc": now.isoformat(),
        "generator": generator,
        "git_head_for_reference_only": commit,
        "generated_with_captured_source": generated,
        "provenance_note": (
            "Generated by the captured working-tree source."
            if generated else
            "Existing STL files preserved unchanged; captured source may be newer than these files."
        ),
        "identity": identity,
        "sha256": files,
    }
    (destination / "manifest.json").write_text(
        json.dumps(metadata, indent=2) + "\n", encoding="utf-8"
    )
    print(f"archived {family}: {destination.relative_to(ROOT)}")
    return destination


def preserve_models(family: str):
    """Wrap a generator main without changing its geometry or output paths."""
    def decorate(main):
        @functools.wraps(main)
        def wrapped(*args, **kwargs):
            # Existing generators write relative to the caller's working folder.
            output_dir = Path(FAMILIES[family][1]).resolve()
            snapshot(family, output_dir)
            result = main(*args, **kwargs)
            snapshot(family, output_dir, generated=True)
            return result
        return wrapped
    return decorate


if __name__ == "__main__":
    # Safe initial migration: copy current files, never regenerate or move them.
    for family, (_, directory) in FAMILIES.items():
        snapshot(family, ROOT / directory)
